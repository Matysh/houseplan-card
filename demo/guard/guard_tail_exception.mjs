// Проба #404 AC1: исключение в самом хвосте, без обращений к странице после.
//
// Это единственная слепая зона, из-за которой заводился #404: смок всё измерил,
// печатает результат, а карточка в это время бросает. Событие `pageerror`
// приходит асинхронно, и до починки счётчик читался раньше доставки.
//
// Файл ОБЯЗАН завершаться ненулевым кодом. Ноль означает, что гард снова слеп.
import { launch, finish } from '../serve.mjs';

const { browser, page } = await launch();
await page.evaluate(() => { setTimeout(() => { throw new Error('guard-tail-exception'); }, 0); });
// Ни одного обращения к странице после этой строки: round-trip обязан сделать
// сам гард, иначе доказательство ничего не доказывает.
await finish(browser, { probe: 'tail exception' });
