import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
import {generateVolume, loadVolumeModels, parseVolumeSvg} from '../scripts/generate-furniture-volume.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const packRoot=join(root,'assets/furniture/houseplan-0.4.1');
const pack=JSON.parse(readFileSync(join(packRoot,'pack.json'),'utf8'));

test('#1451 volume generator checks all 60 source models without rewriting generated bytes',()=>{
  const paths=['src/furniture-volume.generated.ts','src/furniture-gallery-catalog.generated.ts'];
  const before=paths.map(path=>readFileSync(join(root,path)));
  assert.equal(generateVolume(root,true),60);
  paths.forEach((path,i)=>assert.deepEqual(readFileSync(join(root,path)),before[i]));
});

test('#1451 volume catalogue refuses missing, unknown and duplicated model identities',()=>{
  const temporary=mkdtempSync(join(tmpdir(),'hp-volume-catalog-'));
  try{
    const symbols=['sofa','coffee_table'].map(id=>pack.symbols.find(symbol=>symbol.id===id));
    const directory=join(temporary,'svg/volume');mkdirSync(directory,{recursive:true});
    const savePack=value=>writeFileSync(join(temporary,'pack.json'),JSON.stringify({symbols:value}));
    savePack(symbols);
    const copy=id=>copyFileSync(join(packRoot,'svg/volume',id+'.svg'),join(directory,id+'.svg'));
    copy('sofa');
    assert.throws(()=>loadVolumeModels(temporary),/missing model coffee_table/);
    copy('coffee_table');
    assert.deepEqual(Object.keys(loadVolumeModels(temporary)),['coffee_table','sofa']);
    writeFileSync(join(directory,'unknown.svg'),'<svg/>');
    assert.throws(()=>loadVolumeModels(temporary),/unknown model unknown/);
    rmSync(join(directory,'unknown.svg'));
    savePack([symbols[0],symbols[0]]);
    assert.throws(()=>loadVolumeModels(temporary),/duplicate catalog id/);
    savePack([]);
    assert.throws(()=>loadVolumeModels(temporary),/catalog is empty/);
  }finally{rmSync(temporary,{recursive:true,force:true});}
});

test('#1451 inert SVG format rejects concatenated attributes and empty optional geometry',()=>{
  const symbol={id:'probe',width_cm:100,depth_cm:100};
  const source='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" data-hp-volume-schema="2" data-hp-model="probe" data-hp-back="top">'
    +'<rect data-hp-part="body" x="10" y="10" width="80" height="80" rx="10" data-hp-radius-ratio="0.1" data-hp-z-min-cm="0" data-hp-z-max-cm="20" /></svg>';
  assert.equal(parseVolumeSvg(source,symbol).length,1);
  for(const invalid of [source.replace('x="10" y=','x="10"y='),
    ...['data-hp-plane','data-hp-inset-cm','data-hp-base-scale','data-hp-top-scale']
      .map(name=>source.replace('/></svg>',`${name}="" /></svg>`))]){
    assert.notEqual(invalid,source);
    assert.throws(()=>parseVolumeSvg(invalid,symbol),/Furniture volume/);
  }
});

test('#1451 importing the volume generator does not inspect a catalogue, generate or print CLI output',()=>{
  const temporary=mkdtempSync(join(tmpdir(),'hp-volume-import-'));
  try{
    const scripts=join(temporary,'scripts');mkdirSync(scripts);
    for(const file of ['generate-furniture-volume.mjs','spawn-portable.mjs'])copyFileSync(join(root,'scripts',file),join(scripts,file));
    // There is deliberately no pack or src directory: accidental CLI work on
    // import cannot borrow the checkout or mutate its generated registries.
    const url=pathToFileURL(join(scripts,'generate-furniture-volume.mjs')).href;
    const result=spawnSync(process.execPath,['--input-type=module','-e',`await import(${JSON.stringify(url)});`],
      {cwd:temporary,encoding:'utf8'});
    assert.equal(result.status,0,result.stderr);
    assert.equal(result.stdout,'');assert.equal(result.stderr,'');
  }finally{rmSync(temporary,{recursive:true,force:true});}
});
