/** Finite local UI inventory. Build-time only; never ship @mdi/js as a dynamic lookup. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as mdi from '@mdi/js';
import { isMainModule } from './spawn-portable.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = 'src/standalone-icons.generated.ts';
export function renderStandaloneIcons(base = root) {
  const files = directory => readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? files(path) : entry.name.endsWith('.ts') && relative(base, path).replaceAll('\\', '/') !== output ? [path] : [];
  });
  const names = new Set(['help-circle-outline']);
  for (const file of files(resolve(base, 'src'))) for (const match of readFileSync(file, 'utf8').matchAll(/mdi:([a-z0-9-]+)/g)) names.add(match[1]);
  const paths = Object.fromEntries([...names].sort().flatMap(name => {
    const symbol = 'mdi' + name.replace(/(^|-)(\w)/g, (_, __, letter) => letter.toUpperCase());
    return typeof mdi[symbol] === 'string' ? [[`mdi:${name}`, mdi[symbol]]] : [];
  }));
  return '// Generated by scripts/standalone-icons.mjs from finite source references.\n'
    + '// MDI 7.4.47, Apache-2.0; see THIRD_PARTY_NOTICES.md and custom_components/houseplan/licenses/mdi.txt.\n'
    + 'export const STANDALONE_ICON_PATHS: Readonly<Record<string, string>> = Object.freeze('
    + JSON.stringify(paths, null, 2) + ');\n';
}
if (isMainModule(import.meta.url)) {
  const text = renderStandaloneIcons();
  if (process.argv.includes('--check')) {
    if (readFileSync(resolve(root, output), 'utf8') !== text) throw Error('Finite standalone icon inventory is stale');
  } else writeFileSync(resolve(root, output), text);
}
