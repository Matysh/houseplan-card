#!/usr/bin/env node
// Generated filters and job recipes: edit validate.yml / path domains, regenerate.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { unitGroups } from './unit-groups.mjs';
import { profilePaths } from './ci-profile-paths.mjs';
import { toolingDependencyPaths } from './task-check-scope.mjs';
import { isMainModule } from './spawn-portable.mjs';
import { executionHeader } from './ci-registry-inputs.mjs';

function jobsOf(text) {
  text = text.slice(text.indexOf('\njobs:\n') + '\njobs:\n'.length);
  const jobs = new Map(), marks = [...text.matchAll(/^  ([\w-]+):\s*$/gm)];
  for (let i = 0; i < marks.length; i++) jobs.set(marks[i][1], text.slice(marks[i].index, marks[i + 1]?.index).trimEnd() + '\n');
  return jobs;
}
function header(profile, paths, displayName, execution = '') {
  const filters = paths.map(p => `      - '${p}'`).join('\n');
  return [
    '# Generated by node scripts/ci-profiles.mjs --write (#980).',
    '# The shared display name preserves the existing main workflow_run trigger.',
    `name: ${displayName}`, `run-name: 'CI ${profile} · \${{ github.ref_name }}'`, '',
    'on:', '  push:', '    branches:', "      - '**'", "      - '!review-material/**'", "      - '!ci-proofs'",
    '    paths:', filters, '  pull_request:', '    paths:', filters, '',
    'concurrency:', `  group: validate-${profile}-\${{ github.event.pull_request.number || github.ref }}`,
    '  cancel-in-progress: true', '', ...(execution.trim() ? [execution.trimEnd(), ''] : []), 'jobs:', '',
  ].join('\n');
}
const artifact = `      - name: Опубликовать proof точной попытки
        if: always()
        uses: actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a # v7
        with:
          name: ci-proof-\${{ github.run_id }}-\${{ github.run_attempt }}
          path: artifacts/ci-proof/proof.json
          retention-days: 30
          if-no-files-found: error
`;
const eventStep = `      - name: Полный диапазон события
        id: route
        env:
          BEFORE_SHA: \${{ github.event.before }}
          BASE_SHA: \${{ github.event.pull_request.base.sha }}
          HEAD_SHA: \${{ github.sha }}
          EVENT_NAME: \${{ github.event_name }}
        run: node scripts/ci-profile-event.mjs
`;
function fastProof(profile) {
  return `      - name: Зафиксировать progress proof
        if: always()
        env:
          CI_WORKFLOW: validate-${profile}.yml
          CI_RESULT: \${{ job.status }}
        run: node scripts/ci-profile-proof.mjs
${artifact}`;
}
export function generatedProfiles(root = process.cwd()) {
  const canonical = readFileSync(resolve(root, '.github/workflows/validate.yml'), 'utf8').replace(/\r\n/g, '\n');
  const displayName = canonical.match(/^name:\s*(.+)$/m)?.[1];
  if (!displayName) throw Error('canonical workflow has no display name');
  const toolingTests = unitGroups(root).tooling;
  const paths = profilePaths(toolingTests, toolingDependencyPaths(toolingTests, root)), jobs = jobsOf(canonical);
  const product = [...jobs].filter(([id]) => id !== 'tooling').map(([id, text]) => id === 'proof'
    ? text.replace(/, tooling(?=,|\])/, '').replace('          CI_EVENT:', '          CI_WORKFLOW: validate-product.yml\n          CI_EVENT:')
      .replace('          ref: ${{ github.sha }}\n', "          ref: ${{ github.sha }}\n          fetch-depth: 0\n          filter: 'blob:none'\n")
      .replace('      - name: Собрать единый CI proof', eventStep.replace('ci-profile-event.mjs', 'ci-profile-event.mjs --candidate') + '      - name: Собрать единый CI proof')
      .replace('          REQUEST_FULL:', '          CI_REQUIRED_PROFILES: ${{ steps.route.outputs.profiles }}\n          REQUEST_FULL:') : text).join('\n');
  const preflight = jobs.get('preflight');
  const docs = preflight.trimEnd() + '\n' + fastProof('docs');
  const changes = `  changes:
    name: Классификация профиля CI
    runs-on: ubuntu-24.04
    timeout-minutes: 2
    outputs:
      integration: \${{ steps.route.outputs.integration }}
      tooling: 'true'
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7
        with: { fetch-depth: 0, filter: 'blob:none' }
      - uses: actions/setup-node@820762786026740c76f36085b0efc47a31fe5020 # v7
        with: { node-version: 22 }
${eventStep}`;
  // Tooling retains the same no-build test recipe. HACS/Hassfest only for .github.
  const tooling = [preflight, changes, jobs.get('tooling'), jobs.get('hacs'), jobs.get('hassfest')].join('\n')
    + `\n  proof:
    name: Доказательство выполненных проверок
    if: always()
    needs: [preflight, changes, tooling, hacs, hassfest]
    runs-on: ubuntu-24.04
    timeout-minutes: 2
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7
      - uses: actions/setup-node@820762786026740c76f36085b0efc47a31fe5020 # v7
        with: { node-version: 22 }
      - name: Зафиксировать progress proof
        env:
          CI_WORKFLOW: validate-tooling.yml
          NEEDS_JSON: \${{ toJSON(needs) }}
        run: node scripts/ci-profile-proof.mjs
${artifact}`;
  return new Map([
    ['scripts/ci-profile-paths.json', JSON.stringify(paths, null, 2) + '\n'],
    ['.github/workflows/validate-product.yml', header('product', paths.product, displayName, executionHeader(canonical)) + product],
    ['.github/workflows/validate-docs.yml', header('docs', paths.docs, displayName, executionHeader(canonical)) + docs],
    ['.github/workflows/validate-tooling.yml', header('tooling', paths.tooling, displayName, executionHeader(canonical)) + tooling],
  ]);
}
if (isMainModule(import.meta.url)) {
  for (const [path, expected] of generatedProfiles()) {
    if (process.argv.includes('--write')) writeFileSync(path, expected);
    else if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== expected) throw Error(`stale ${path}: node scripts/ci-profiles.mjs --write`);
  }
}
