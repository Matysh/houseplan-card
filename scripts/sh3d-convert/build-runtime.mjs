/** Reproducible tool-only bundle. It is NOT a House Plan card bundle. */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rollup } from 'rollup';
import { nodeResolve } from '@rollup/plugin-node-resolve';
import { isMainModule } from '../spawn-portable.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
export const RUNTIME_PATH = join(HERE, 'geometry-runtime.generated.mjs');

export async function buildGeometryRuntime() {
  const compile = spawnSync(process.execPath, [
    join(ROOT, 'node_modules/typescript/bin/tsc'), '-p', join(HERE, 'tsconfig.json'),
  ], { cwd: ROOT, encoding: 'utf8', timeout: 120000, maxBuffer: 4 * 1024 * 1024 });
  if (compile.status !== 0) throw new Error(`Converter geometry build failed:\n${compile.stdout || ''}${compile.stderr || ''}`);
  const bundle = await rollup({
    input: join(HERE, '.build/scripts/sh3d-convert/geometry-entry.js'),
    plugins: [nodeResolve()],
    onwarn(warning, warn) {
      if (warning.code === 'UNRESOLVED_IMPORT') throw new Error(warning.message);
      warn(warning);
    },
  });
  try {
    const { output } = await bundle.generate({ format: 'es', inlineDynamicImports: true });
    if (output.length !== 1 || output[0].type !== 'chunk' || output[0].imports.length)
      throw new Error('Converter geometry must be one self-contained ES module');
    return '// Generated by build-runtime.mjs from canonical src modules. Do not edit.\n' + output[0].code.replace(/\r\n/g, '\n');
  } finally { await bundle.close(); }
}

export async function syncGeometryRuntime(check = false) {
  const code = await buildGeometryRuntime();
  if (check) {
    if (readFileSync(RUNTIME_PATH, 'utf8') !== code)
      throw new Error('Converter runtime is stale: node scripts/sh3d-convert/build-runtime.mjs');
  } else writeFileSync(RUNTIME_PATH, code);
  return code;
}

if (isMainModule(import.meta.url)) {
  await syncGeometryRuntime(process.argv.includes('--check'));
  console.log('ok: converter geometry runtime');
}
