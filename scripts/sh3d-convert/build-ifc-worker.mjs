import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { rollup } from 'rollup';
import terser from '@rollup/plugin-terser';
import { nodeResolve } from '@rollup/plugin-node-resolve';
import { isMainModule } from '../spawn-portable.mjs';
export const WORKER_PATH = fileURLToPath(new URL('./page/ifc-worker.generated.mjs', import.meta.url));
export async function syncIfcWorker(check = false) {
  const bundle = await rollup({ input: fileURLToPath(new URL('./ifc-worker-entry.mjs', import.meta.url)), plugins: [{
    name: 'shared-embedded-ifc-engine',
    resolveId(source) { if (source.endsWith('/vendor/ifc/engine.mjs')) return 'virtual:ifc-engine'; },
    load(id) { if (id === 'virtual:ifc-engine') return 'export const createIfcEngine = globalThis.__HOUSEPLAN_IFC_ENGINE__;'; },
  }, nodeResolve({ browser: true }), terser({ compress: true, mangle: true, format: { comments: false } })],
  onwarn(w, warn) { if (w.code === 'UNRESOLVED_IMPORT') throw Error(w.message); warn(w); } });
  try {
    const { output } = await bundle.generate({ format: 'iife', inlineDynamicImports: true });
    if (output.length !== 1 || output[0].imports.length) throw Error('IFC Worker must be self-contained');
    const source = `// Generated by build-ifc-worker.mjs; engine is supplied once by the host.\nexport const IFC_WORKER_SOURCE = ${JSON.stringify(output[0].code)};\n`;
    if (check) { if (readFileSync(WORKER_PATH, 'utf8') !== source) throw Error('Stale IFC Worker'); }
    else writeFileSync(WORKER_PATH, source);
    return output[0].code;
  } finally { await bundle.close(); }
}
if (isMainModule(import.meta.url)) await syncIfcWorker(process.argv.includes('--check'));
