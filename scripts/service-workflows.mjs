#!/usr/bin/env node
// #1040: mechanical recipe for the eight mirrored service ingress files.
import { readFileSync, writeFileSync } from 'node:fs';
import { isMainModule } from './spawn-portable.mjs';

const expression = text => '${{ ' + text + ' }}';
const PREFIX = 'Matysh/houseplan-card/.github/workflows/';
export const ROUTES = Object.freeze({
  'process.yml': { name: 'Ревью-конвейер',
    triggers: '  issues:\n    types: [labeled]',
    filter: "github.event_name == 'workflow_dispatch' || github.event.label.name == 'S4-spec-review' || github.event.label.name == 'S7-code-review'",
    title: "github.event_name == 'workflow_dispatch' && fromJSON(inputs.delivery || '{}').title || format('relay process #{0} · {1} · {2}', github.event.issue.number, github.event.label.name, github.event.issue.title)",
    permissions: { contents: 'read', issues: 'write' } },
  'process-resume.yml': { name: 'Продолжение ревью после Validate',
    triggers: '  workflow_run:\n    workflows: ["Проверка (CI)", "Полные бенчмарки производительности"]\n    types: [completed]',
    filter: "github.event_name == 'workflow_dispatch' || (github.event.workflow_run.repository.full_name == github.repository && github.event.workflow_run.head_repository.full_name == github.repository)",
    permissions: { contents: 'write', actions: 'write', issues: 'write' } },
  'process-reconcile.yml': { name: 'Сверка очереди ревью', triggers: "  schedule:\n    - cron: '7,37 * * * *'",
    parameters: { apply: { type: 'boolean', default: true, description: 'Recover lost requests and publish diagnostics' } },
    permissions: { actions: 'read', contents: 'read', issues: 'read' } },
  'nightly.yml': { name: 'Ночной полный прогон dev', triggers: "  schedule:\n    - cron: '17 2 * * *'",
    permissions: { actions: 'write', contents: 'read' } },
  'mutation-gate.yml': { name: 'Мутационный гейт', triggers: "  schedule:\n    - cron: '43 0 * * *'",
    concurrency: "format('mutation-gate-{0}', needs.event.outputs.event_name)", cancel: true,
    parameters: { ref: { type: 'string', default: 'dev', description: 'Git ref whose mutation guards must be proved' } },
    permissions: { contents: 'read', actions: 'read', issues: 'write' } },
  'process-metrics.yml': { name: 'Метрики процесса', triggers: "  schedule:\n    - cron: '23 5 * * 1'",
    parameters: { days: { type: 'string', default: '7', description: 'Window in days' } },
    permissions: { contents: 'read', actions: 'read', issues: 'read' } },
  'ship-review.yml': { name: 'Бета: пакетное ревью ship',
    concurrency: "format('ship-review-{0}', fromJSON(needs.event.outputs.parameters).tag)", cancel: false,
    parameters: { tag: { type: 'string', default: '', description: 'Beta tag or nightly' }, candidate: { type: 'string', default: '', description: 'Exact candidate SHA; empty means dev' }, force: { type: 'boolean', default: false, description: 'Review even when already covered' } },
    permissions: { contents: 'read', issues: 'read' } },
  'beta-derived.yml': { name: 'Бета: производные артефакты на dev',
    concurrency: "'beta-derived'", cancel: false,
    parameters: Object.fromEntries(['tag', 'docs_expect_change', 'golden_run', 'golden_expect_change', 'golden_expect_new'].map(key => [key, { type: 'string', default: '', description: key }])),
    permissions: { contents: 'read', actions: 'read' } },
});

export function serviceWorkflow(file) {
  const route = ROUTES[file];
  const lines = [`# Generated by scripts/service-workflows.mjs (#1040); mirrored to main.`,
    `# main only delivers; authenticated work runs on dev. Failures are not hidden.`,
    `name: ${JSON.stringify(route.name)}`,
    `run-name: ${JSON.stringify(expression(route.title || "github.ref == 'refs/heads/dev' && format('dev · {0}', github.workflow) || format('relay · {0}', github.workflow)"))}`,
    '', 'on:', ...(route.triggers ? [route.triggers] : []), '  workflow_dispatch:', '    inputs:',
    '      delivery:', '        description: "Internal immutable origin locator; leave empty for an ordinary dev dispatch"',
    '        type: string', '        required: false', '        default: ""'];
  for (const [key, parameter] of Object.entries(route.parameters || {})) {
    lines.push(`      ${key}:`, `        description: ${JSON.stringify(parameter.description)}`, `        type: ${parameter.type}`, '        required: false', `        default: ${JSON.stringify(parameter.default)}`);
  }
  lines.push('', 'permissions:', '  contents: read', '', 'jobs:', '  event:',
    ...(route.filter ? [`    if: ${route.filter}`] : []),
    '    permissions:', '      contents: write', '      actions: write',
    `    uses: ${PREFIX}_service-event.yml@dev # #1040: trusted delivery code from dev`, '    with:', `      workflow: ${file}`,
    `      parameters: ${expression('toJSON(inputs)')}`,
    '    secrets: inherit', '  dev:', '    needs: event',
    `    if: needs.event.outputs.accepted == 'true'`, '    permissions:');
  for (const [scope, level] of Object.entries(route.permissions)) lines.push(`      ${scope}: ${level}`);
  if (route.concurrency) lines.push('    concurrency:', `      group: ${expression(route.concurrency)}`, `      cancel-in-progress: ${route.cancel}`);
  lines.push(`    uses: ${PREFIX}_${file}@dev # #1040: reviewed execution body from dev`, '    with:',
    `      source_event: ${expression('needs.event.outputs.event')}`,
    `      source_event_name: ${expression('needs.event.outputs.event_name')}`);
  for (const key of Object.keys(route.parameters || {})) lines.push(`      ${key}: ${expression(`fromJSON(needs.event.outputs.parameters).${key}`)}`);
  lines.push('    secrets: inherit', '');
  return lines.join('\n');
}
if (isMainModule(import.meta.url)) {
  for (const file of Object.keys(ROUTES)) {
    const path = new URL(`../.github/workflows/${file}`, import.meta.url);
    const expected = serviceWorkflow(file);
    if (process.argv.includes('--write')) writeFileSync(path, expected);
    else if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== expected) throw Error(`${file} differs; run node scripts/service-workflows.mjs --write`);
  }
}
