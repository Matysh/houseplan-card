// #1068: authenticate four derived counters without executing the material.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { lstatSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const STATUS_COUNTER_PATH = 'docs/STATUS.md';
export const STATUS_COUNTER_BEGIN = '<!-- status-snapshot:begin — generated by `node scripts/status-snapshot.mjs --write`; do not edit by hand -->';
export const STATUS_COUNTER_END = '<!-- status-snapshot:end -->';
const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const STATUS_COUNTER_POLICY_PATHS = Object.freeze([
  'scripts/inventory.mjs', 'scripts/status-snapshot.mjs', 'scripts/status-counter-equivalence.mjs',
]);
const SOURCES = STATUS_COUNTER_POLICY_PATHS;
// Exact counter implementation used by both original and rebased #1063 trees.
const LEGACY = ['19f51ce57b618120cfe13e3b826428009032c27d', 'dedd03ed752f74b4e81ad7ed809bfdacb466d82c'];
const MAX_BYTES = 64 * 1024 * 1024;
const REGULAR = new Set(['100644', '100755']);
const KEYS = ['node', 'pure', 'ha', 'smokes'];
const RULES = [
  { key: 'node', id: 'node', label: 'Node unit (frontend + tooling)', path: /^test\/[^/]*\.test\.mjs$/, tests: /^\s*(test|it)\(/gm },
  { key: 'pure', id: 'backend-pure', label: 'pure backend (pytest, no HA)', path: /^tests_backend\/test_(?!ha_)[^/]*\.py$/, tests: /^\s*(?:async\s+)?def test_/gm },
  { key: 'ha', id: 'backend-ha', label: 'HA-harness backend (CI, py3.13)', path: /^tests_backend\/test_ha_[^/]*\.py$/, tests: /^\s*(?:async\s+)?def test_/gm },
  { key: 'smokes', id: 'smokes', label: 'browser smokes (headless chromium)', path: /^demo\/smoke_[^/]*\.mjs$/ },
];
const requireThat = (condition, message) => { if (!condition) throw Error('status counters: ' + message); };
const blobId = bytes => createHash('sha1').update('blob ' + bytes.length + '\0').update(bytes).digest('hex');
const ruleFor = path => RULES.find(rule => rule.path.test(path));
const validPath = path => typeof path === 'string' && !/[\\\0\r\n]/.test(path)
  && path.split('/').every(part => part && part !== '.' && part !== '..');

function parseStatusCounters(text) {
  requireThat(typeof text === 'string' && Buffer.byteLength(text) <= MAX_BYTES, 'unreadable/oversized snapshot');
  const start = text.indexOf(STATUS_COUNTER_BEGIN), end = text.indexOf(STATUS_COUNTER_END);
  requireThat(start >= 0 && end > start && (start === 0 || text[start - 1] === '\n')
    && text.indexOf(STATUS_COUNTER_BEGIN, start + 1) < 0 && text.indexOf(STATUS_COUNTER_END, end + 1) < 0,
  'expected one exact generated block');
  const tail = text.slice(end + STATUS_COUNTER_END.length);
  requireThat(!tail || tail.startsWith('\n') || tail.startsWith('\r\n'), 'end marker must occupy one line');
  const block = text.slice(start, end + STATUS_COUNTER_END.length), rawLines = block.split('\n');
  const lines = rawLines.map(line => line.replace(/\r$/, ''));
  requireThat(lines.length === 9 && lines[0] === STATUS_COUNTER_BEGIN && lines[8] === STATUS_COUNTER_END
    && lines[1] === '| Item | State |' && lines[2] === '|---|---|', 'unsupported generated table structure');
  const date = /^\| Generated \| (\d{4}-\d{2}-\d{2}) — rerun \x60node scripts\/status-snapshot\.mjs\x60 for the current tree \|$/.exec(lines[3]);
  requireThat(date && Number.isFinite(Date.parse(date[1])) && new Date(date[1]).toISOString().slice(0, 10) === date[1],
    'invalid generated date row');
  requireThat(/^\| Version \| \*\*\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?\*\* in all 7 version sources \(\x60scripts\/release-contract\.mjs\x60\) \|$/.test(lines[4]),
    'unsupported version row');
  const unavailable = 'n/a — tags are not available in this checkout';
  requireThat(lines[5] === '| Latest stable tag | ' + unavailable + ' |'
    || /^\| Latest stable tag \| \x60v\d+\.\d+\.\d+\x60 \|$/.test(lines[5]), 'unsupported stable tag row');
  requireThat(lines[6] === '| Latest prerelease tag | ' + unavailable + ' |'
    || /^\| Latest prerelease tag \| \x60v\d+\.\d+\.\d+-[0-9A-Za-z.-]+\x60 \|$/.test(lines[6]), 'unsupported prerelease tag row');
  const row = /^\| Tests \| Node unit (0|[1-9]\d*) · pure backend (0|[1-9]\d*) · HA-harness backend (0|[1-9]\d*) · browser smokes (0|[1-9]\d*) \(\x60npm run inventory\x60\) \|$/d.exec(lines[7]);
  requireThat(row, 'unsupported Tests row');
  const counts = Object.fromEntries(KEYS.map((key, i) => [key, Number(row[i + 1])]));
  requireThat(Object.values(counts).every(Number.isSafeInteger), 'unsafe counter value');
  const rowStart = start + rawLines.slice(0, 7).reduce((sum, line) => sum + line.length + 1, 0);
  return { counts, spans: row.indices.slice(1).map(([a, b], i) => ({ start: rowStart + a, end: rowStart + b, key: KEYS[i] })) };
}

/** Every byte other than the four canonical digit spans stays in the identity. */
export function replaceStatusCounters(text, counts) {
  requireThat(counts && Object.keys(counts).length === KEYS.length
    && KEYS.every(key => Number.isSafeInteger(counts[key]) && counts[key] >= 0), 'invalid replacement counts');
  for (const span of parseStatusCounters(text).spans.reverse())
    text = text.slice(0, span.start) + counts[span.key] + text.slice(span.end);
  return text;
}
export function normalizeStatusCounters(text) {
  return replaceStatusCounters(text, Object.fromEntries(KEYS.map(key => [key, 0])));
}

/** Pure trusted algorithm; read returns data, never an imported test module. */
export function countStatusCounterEntries({ paths, read }) {
  requireThat(Array.isArray(paths) && new Set(paths).size === paths.length, 'duplicate/missing input paths');
  const counts = Object.fromEntries(KEYS.map(key => [key, 0]));
  for (const path of paths) {
    const rule = ruleFor(path);
    if (!rule) continue;
    requireThat(validPath(path), 'unsafe input path');
    counts[rule.key] += rule.tests ? (read(path).toString('utf8').match(rule.tests) || []).length : 1;
  }
  return counts;
}
const inventoryRows = counts => RULES.map(({ key, id, label }) => ({ id, label, count: counts[key] }));
function regularFile(root, path) {
  requireThat(validPath(path), 'unsafe file path');
  const parts = path.split('/');
  for (let i = 1; i <= parts.length; i++) {
    const stat = lstatSync(join(root, ...parts.slice(0, i)));
    requireThat(!stat.isSymbolicLink() && (i === parts.length ? stat.isFile() : stat.isDirectory()),
      'nonregular file or parent: ' + path);
  }
}
function filesystemInputs(root) {
  return ['test', 'tests_backend', 'demo'].flatMap(dir => {
    requireThat(lstatSync(join(root, dir)).isDirectory() && !lstatSync(join(root, dir)).isSymbolicLink(), 'nonregular input directory: ' + dir);
    return readdirSync(join(root, dir)).map(name => dir + '/' + name).filter(path => ruleFor(path));
  });
}
/** Existing filesystem generator uses the same four rules, including fixtures. */
export function statusCounterInventory(root = process.cwd()) {
  const paths = filesystemInputs(root);
  for (const path of paths) regularFile(root, path);
  return inventoryRows(countStatusCounterEntries({ paths, read: path => readFileSync(join(root, path)) }));
}

function remaining(deadline) {
  const ms = Math.floor(deadline - Date.now());
  requireThat(Number.isFinite(ms) && ms > 0, 'read deadline exceeded');
  return ms;
}
function gitReader(root, deadline) {
  // Hooks/exported Git variables must not redirect a read to another checkout,
  // index, object database or config despite the explicit -C root.
  const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !/^GIT_/i.test(key)));
  return (args, input) => {
    const bytes = execFileSync('git', ['--no-replace-objects', '-C', root, ...args], {
      input, maxBuffer: MAX_BYTES, timeout: remaining(deadline), killSignal: 'SIGKILL',
      stdio: ['pipe', 'pipe', 'pipe'],
      env: { ...env, GIT_NO_LAZY_FETCH: '1', GIT_NO_REPLACE_OBJECTS: '1', GIT_ALLOW_PROTOCOL: '', GIT_TERMINAL_PROMPT: '0' },
    });
    remaining(deadline);
    return bytes;
  };
}
function supportedPolicy(entries) {
  const identity = paths => createHash('sha256').update(JSON.stringify(paths.map(path =>
    [path, entries.get(path).mode, entries.get(path).oid]))).digest('hex');
  const current = SOURCES.every(path => {
    const entry = entries.get(path);
    const trusted = Buffer.from(readFileSync(resolve(ROOT, path), 'utf8').replace(/\r\n/g, '\n'));
    return entry?.mode === '100644' && entry.oid === blobId(trusted);
  });
  if (current) return identity(SOURCES);
  if (!entries.has(SOURCES[2]) && SOURCES.slice(0, 2).every((path, i) =>
    entries.get(path)?.mode === '100644' && entries.get(path)?.oid === LEGACY[i])) return identity(SOURCES.slice(0, 2));
  throw Error('status counters: unsupported generator sources');
}
function immutableInputs(entries) {
  for (const dir of ['test', 'tests_backend', 'demo'])
    requireThat([...entries.keys()].some(path => path.startsWith(dir + '/')), 'missing counter input directory: ' + dir);
  const paths = [];
  for (const [path, entry] of entries) {
    // A directory named *.test.mjs makes the filesystem generator fail too.
    const direct = path.split('/').slice(0, 2).join('/');
    if (ruleFor(direct)) requireThat(direct === path && entry.type === 'blob' && REGULAR.has(entry.mode), 'nonregular counter input: ' + path);
    if (ruleFor(path)) paths.push(path);
  }
  return paths;
}
function readBlobs(run, entries, paths) {
  const oids = [...new Set(paths.map(path => {
    const entry = entries.get(path);
    requireThat(entry?.type === 'blob' && REGULAR.has(entry.mode), 'missing/nonregular blob: ' + path);
    return entry.oid;
  }))];
  const objects = new Map();
  if (!oids.length) return () => { throw Error('status counters: absent blob'); };
  const bytes = run(['cat-file', '--batch'], oids.join('\n') + '\n');
  let at = 0;
  for (const oid of oids) {
    const end = bytes.indexOf(10, at), header = bytes.subarray(at, end).toString('utf8').split(' '), size = Number(header[2]);
    requireThat(end >= at && header[0] === oid && header[1] === 'blob' && Number.isSafeInteger(size) && size >= 0
      && end + size + 1 < bytes.length && bytes[end + size + 1] === 10, 'missing/corrupt immutable blob');
    const content = bytes.subarray(end + 1, end + 1 + size);
    requireThat(blobId(content) === oid, 'blob bytes differ from immutable OID');
    objects.set(oid, content); at = end + size + 2;
  }
  requireThat(at === bytes.length, 'unexpected batch bytes');
  return path => {
    const value = objects.get(entries.get(path)?.oid);
    requireThat(value, 'unread counter blob: ' + path);
    return value;
  };
}

/** Unsupported or stale snapshots are ordinary misses, never equivalence. */
export function validateStatusCounters({ root = process.cwd(), ref, deadline = Date.now() + 8000 }) {
  try {
    requireThat(typeof ref === 'string' && ref.length > 0 && !ref.startsWith('-') && !/[\0\r\n]/.test(ref), 'invalid immutable ref');
    const run = gitReader(root, deadline);
    const tree = run(['rev-parse', '--verify', ref + '^{tree}']).toString('utf8').trim();
    requireThat(/^[a-f0-9]{40}$/.test(tree), 'invalid immutable tree');
    const rows = run(['ls-tree', '-rz', '--full-tree', tree]).toString('utf8').split('\0').filter(Boolean);
    const entries = new Map();
    for (const row of rows) {
      const match = /^(\d+) (\w+) ([a-f0-9]{40})\t(.+)$/.exec(row);
      requireThat(match && validPath(match[4]) && !entries.has(match[4]), 'invalid/duplicate tree entry');
      entries.set(match[4], { mode: match[1], type: match[2], oid: match[3] });
    }
    const policy = supportedPolicy(entries), paths = immutableInputs(entries);
    const read = readBlobs(run, entries, [STATUS_COUNTER_PATH, ...paths.filter(path => ruleFor(path).tests)]);
    const text = read(STATUS_COUNTER_PATH).toString('utf8'), parsed = parseStatusCounters(text);
    const counts = countStatusCounterEntries({ paths, read });
    requireThat(KEYS.every(key => parsed.counts[key] === counts[key]), 'snapshot counters do not match immutable inputs');
    remaining(deadline);
    return { ok: true, text, normalized: normalizeStatusCounters(text), counts, tree, policy,
      mode: entries.get(STATUS_COUNTER_PATH).mode };
  } catch (error) { return { ok: false, reason: error.message }; }
}

/** Combined worktree repair: tracked regular inputs only, no writes or imports. */
export function refreshStatusCounterText({ root = process.cwd(), text, deadline = Date.now() + 8000 }) {
  const run = gitReader(root, deadline), entries = new Map();
  for (const row of run(['ls-files', '--stage', '-z']).toString('utf8').split('\0').filter(Boolean)) {
    const match = /^(\d+) ([a-f0-9]{40}) ([0-3])\t(.+)$/.exec(row);
    requireThat(match && validPath(match[4]), 'invalid index entry');
    const path = match[4];
    if (ruleFor(path) || SOURCES.includes(path)) {
      requireThat(match[3] === '0' && !entries.has(path) && REGULAR.has(match[1]), 'conflicted/nonregular input: ' + path);
      entries.set(path, { mode: match[1], oid: match[2], type: 'blob' });
    }
  }
  const paths = filesystemInputs(root);
  for (const path of paths) requireThat(entries.has(path), 'untracked counter input: ' + path);
  const contents = new Map();
  let total = 0;
  for (const [path, entry] of entries) {
    regularFile(root, path);
    requireThat(lstatSync(join(root, path)).size <= MAX_BYTES - total, 'oversized worktree inputs');
    const bytes = readFileSync(join(root, path));
    total += bytes.length;
    requireThat(total <= MAX_BYTES, 'oversized worktree inputs');
    // Rebase repairs describe the combined index, never concurrent unstaged
    // edits. Accept ordinary checkout CRLF conversion, not changed contents.
    requireThat(blobId(bytes) === entry.oid
      || blobId(Buffer.from(bytes.toString('utf8').replace(/\r\n/g, '\n'))) === entry.oid,
    'modified ' + (SOURCES.includes(path) ? 'generator source: ' : 'counter input: ') + path);
    contents.set(path, bytes);
  }
  supportedPolicy(entries);
  const tracked = [...entries.keys()].filter(path => ruleFor(path));
  requireThat(tracked.length === paths.length, 'missing tracked counter input');
  const counts = countStatusCounterEntries({ paths: tracked, read: path => contents.get(path) });
  const updated = replaceStatusCounters(text, counts);
  remaining(deadline);
  return { text: updated, counts, changed: updated !== text };
}
